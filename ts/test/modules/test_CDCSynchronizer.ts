// Generate CDCSynchronizer variants and the inputs for verilatorTB/tb_CDCSynchronizer.sv:
//
// 1. Self-checks against the spec: ports, ASYNC_REG on every stage, distinct module names, and
//    the invalid parameters that throw.
// 2. The testbench configurations (TB_CONFIGS), plus sv-examples/CDCSynchronizer/tb/:
//    - CDCSynchronizer_tb_configs.svh: per-configuration DUT name, width and stages
//    - CDCSynchronizer_tb_vectors.svh: one task per timing diagram in the spec
//    - configs.txt: "<config> <DUT .sv path>" per line, read by `make cdcsynchronizer_sim`
//
// Run `make -C verilatorTB cdcsynchronizer_sim` to generate everything, lint each variant with
// -Wall and simulate each configuration.

import { CDCSynchronizer } from 'tssv/lib/modules/CDCSynchronizer'
import { mkdirSync, writeFileSync } from 'fs'
import { diagramTasks } from '../models/wavedromVectors.js'

const SPEC = 'doc/modules/CDCSynchronizer/CDCSynchronizer-spec.md'
const OUT = 'sv-examples/CDCSynchronizer'
const TB_DIR = `${OUT}/tb`

let passed = 0
let failed = 0

function check (label: string, ok: boolean, detail?: string): void {
  if (ok) {
    console.log(`PASS: ${label}`)
    passed++
  } else {
    console.error(`FAIL: ${label}${detail !== undefined ? `\n  ${detail}` : ''}`)
    failed++
  }
}

function expectThrow (label: string, fn: () => unknown, message: string): void {
  try {
    fn()
    check(label, false, 'did not throw')
  } catch (e) {
    const got = (e instanceof Error) ? e.message : String(e)
    check(label, got.includes(message), `expected a message containing '${message}', got '${got}'`)
  }
}

/** write a synchronizer's SV to sv-examples/CDCSynchronizer/<name>/<name>.sv and return it and its path */
function emit (s: CDCSynchronizer): { sv: string, path: string } {
  const dir = `${OUT}/${s.name}`
  mkdirSync(dir, { recursive: true })
  const sv = s.writeSystemVerilog()
  writeFileSync(`${dir}/${s.name}.sv`, sv)
  return { sv, path: `${dir}/${s.name}.sv` }
}

// ============================================ 1. checks against the spec
const SPEC_PORTS = ['clk', 'rst_n', 'd', 'q'].sort().join(' ')

for (const width of [1n, 8n]) {
  for (const stages of [2n, 3n]) {
    const s = new CDCSynchronizer({ width, stages })
    const { sv } = emit(s)
    const ports = Object.keys((s as unknown as { IOs: Record<string, unknown> }).IOs).sort().join(' ')
    check(`${s.name}: ports match the spec`, ports === SPEC_PORTS, `got: ${ports}\n  spec: ${SPEC_PORTS}`)
    // every stage's declaration, and only those, carries ASYNC_REG
    const marked = [...sv.matchAll(/\(\* ASYNC_REG = "TRUE" \*\)\s*logic(?: \[\d+:0\])? (\w+);/g)].map(m => m[1])
    const want = Array.from({ length: Number(stages) }, (_, i) => `sync_${i}`)
    check(`${s.name}: exactly sync_0 to sync_${stages - 1n} carry ASYNC_REG`,
      marked.join(' ') === want.join(' ') && (sv.match(/ASYNC_REG/g) ?? []).length === want.length,
      `got: ${marked.join(' ')}`)
  }
}

const names = [
  { width: 1n },
  { width: 1n, stages: 3n },
  { width: 8n },
  { width: 8n, stages: 4n }
].map(p => new CDCSynchronizer(p).name)
check(`synchronizers that differ in any parameter get different names (${names.join(', ')})`,
  new Set(names).size === names.length)
check('the default name is CDCSynchronizer_<width>_<stages>, with stages defaulting to 2',
  names[0] === 'CDCSynchronizer_1_2' && new CDCSynchronizer({ width: 1n, stages: 2n }).name === names[0])

expectThrow('width 0 throws', () => new CDCSynchronizer({ width: 0n }), 'CDCSynchronizer: width must be at least 1, got 0')
expectThrow('stages 1 throws', () => new CDCSynchronizer({ width: 4n, stages: 1n }), 'CDCSynchronizer: stages must be at least 2, got 1')

// ============================================ 2. testbench configurations
interface TbConfig {
  cfg: string
  width: bigint
  stages: bigint
  /** timing diagrams (SVG names in the spec, without the CDCSynchronizer- prefix) to replay */
  diagrams: string[]
}

const TB_CONFIGS: TbConfig[] = [
  { cfg: 'w1_s2', width: 1n, stages: 2n, diagrams: ['timing'] },
  { cfg: 'w8_s3', width: 8n, stages: 3n, diagrams: [] }
]

mkdirSync(TB_DIR, { recursive: true })
const header = '// Generated by ts/test/modules/test_CDCSynchronizer.ts. Do not edit.\n'
let configs = header
const configList: string[] = []
TB_CONFIGS.forEach((c, i) => {
  const s = new CDCSynchronizer({ width: c.width, stages: c.stages })
  configList.push(`${c.cfg} ${emit(s).path}`)
  configs += `\`${i === 0 ? 'ifdef' : 'elsif'} CFG_${c.cfg}\n`
  configs += `  \`define CFG_NAME "${c.cfg}"\n`
  configs += `  \`define CDC_DUT ${s.name}\n`
  configs += `  \`define WIDTH ${c.width}\n`
  configs += `  \`define STAGES ${c.stages}\n`
  configs += `  \`define RUN_DIAGRAMS ${c.diagrams.map(d => `diagram_${d.replace(/-/g, '_')}();`).join(' ')}\n`
  console.log(`${s.name}: testbench config ${c.cfg}`)
})
configs += '`else\n  `error "define one of the CFG_<config> macros"\n`endif\n'
writeFileSync(`${TB_DIR}/CDCSynchronizer_tb_configs.svh`, configs)
writeFileSync(`${TB_DIR}/configs.txt`, configList.join('\n') + '\n')

// ============================================ 3. timing-diagram vectors
// src_clk launches d; the synchronizer's clk is the slow clock. sync_0 is internal: the
// testbench reads it through a hierarchical reference.
const { sv: vectors, names: diagrams } = diagramTasks(SPEC, 'CDCSynchronizer',
  { clock: 'src_clk', type: 'src_vec_t', fields: ['d'] },
  { clock: 'clk', type: 'dst_vec_t', fields: ['sync_0', 'q'] })
for (const c of TB_CONFIGS) {
  for (const d of c.diagrams) check(`${c.cfg}: the spec has diagram CDCSynchronizer-${d}.svg`, diagrams.includes(d))
}
writeFileSync(`${TB_DIR}/CDCSynchronizer_tb_vectors.svh`, header + vectors)
console.log(`${diagrams.length} timing diagram(s) from ${SPEC} written to ${TB_DIR}/CDCSynchronizer_tb_vectors.svh`)

console.log(`\n${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)
