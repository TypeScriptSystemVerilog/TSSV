// Generate LZC variants and the inputs for verilatorTB/tb_LZC.sv:
//
// 1. Every structural configuration: a 1-bit word (no tree), a 2-bit word (one level), widths
//    that are a power of 2 (no padding) and widths that aren't (padded), up to the 256-bit
//    maximum. Each one's ports are checked against the spec's IO table, and its SV must hold no
//    always_latch. The invalid widths must throw.
// 2. sv-examples/LZC/tb/:
//    - LZC_tb_configs.svh: per-configuration DUT name and width
//    - configs.txt: "<config> <DUT .sv path>" per line, read by `make lzc_sim`
//
// Run `make -C verilatorTB lzc_sim` to generate everything, lint each variant with -Wall and
// check each one against a reference model.

import { LZC, type LZC_Parameters } from 'tssv/lib/modules/LZC'
import { mkdirSync, writeFileSync } from 'fs'

const OUT = 'sv-examples/LZC'
const TB_DIR = `${OUT}/tb`

let passed = 0
let failed = 0

function check (label: string, ok: boolean, detail?: string): void {
  if (ok) {
    console.log(`PASS: ${label}`)
    passed++
  } else {
    console.error(`FAIL: ${label}${detail !== undefined ? `\n  ${detail}` : ''}`)
    failed++
  }
}

function expectThrow (label: string, fn: () => unknown, message: string): void {
  try {
    fn()
    check(label, false, 'did not throw')
  } catch (e) {
    const got = (e instanceof Error) ? e.message : String(e)
    check(label, got.includes(message), `expected a message containing '${message}', got '${got}'`)
  }
}

/** write an LZC's SV to sv-examples/LZC/<name>/<name>.sv and return it and its path */
function emit (lzc: LZC): { sv: string, path: string } {
  const dir = `${OUT}/${lzc.name}`
  mkdirSync(dir, { recursive: true })
  const sv = lzc.writeSystemVerilog()
  writeFileSync(`${dir}/${lzc.name}.sv`, sv)
  return { sv, path: `${dir}/${lzc.name}.sv` }
}

/** the spec's IO table for a width: "<port>:<width>", sorted. zero_num holds 0 to dataWidth */
function specPorts (dataWidth: number): string {
  let countWidth = 1
  while (2 ** countWidth <= dataWidth) countWidth++
  return [`data_in:${dataWidth}`, `zero_num:${countWidth}`, 'is_zero:1'].sort().join(' ')
}

// ============================================ 1. every structural configuration
// 1: no tree; 2: one level; 3, 21, 28: padded; 64, 256: powers of 2, 256 the largest width
const WIDTHS = [1, 2, 3, 21, 28, 64, 256] as const
const emitted = new Map<number, { lzc: LZC, path: string }>()

for (const dataWidth of WIDTHS) {
  const lzc = new LZC({ dataWidth })
  const { sv, path } = emit(lzc)
  emitted.set(dataWidth, { lzc, path })
  const IOs = (lzc as unknown as { IOs: Record<string, { width?: number }> }).IOs
  const ports = Object.entries(IOs).map(([name, io]) => `${name}:${io.width ?? 1}`).sort().join(' ')
  check(`${lzc.name}: ports match the spec`, ports === specPorts(dataWidth), `got:  ${ports}\n  spec: ${specPorts(dataWidth)}`)
  check(`${lzc.name}: no always_latch`, !sv.includes('always_latch'))
}

check('the default name is LZC_<dataWidth>', emitted.get(21)?.lzc.name === 'LZC_21')

for (const bad of [0, 257, 2.5]) {
  expectThrow(`dataWidth ${bad} throws`, () => new LZC({ dataWidth: bad } as unknown as LZC_Parameters),
    `LZC: dataWidth must be an integer from 1 to 256, got ${bad}`)
}

// ============================================ 2. testbench configurations: every width above
mkdirSync(TB_DIR, { recursive: true })
let configs = '// Generated by ts/test/modules/test_LZC.ts. Do not edit.\n'
const configList: string[] = []
WIDTHS.forEach((dataWidth, i) => {
  const e = emitted.get(dataWidth)
  if (e === undefined) throw Error(`no LZC emitted for dataWidth ${dataWidth}`)
  const cfg = `w${dataWidth}`
  configList.push(`${cfg} ${e.path}`)
  configs += `\`${i === 0 ? 'ifdef' : 'elsif'} CFG_${cfg}\n`
  configs += `  \`define CFG_NAME "${cfg}"\n`
  configs += `  \`define LZC_DUT ${e.lzc.name}\n`
  configs += `  \`define WIDTH ${dataWidth}\n`
})
configs += '`else\n  `error "define one of the CFG_<config> macros"\n`endif\n'
writeFileSync(`${TB_DIR}/LZC_tb_configs.svh`, configs)
writeFileSync(`${TB_DIR}/configs.txt`, configList.join('\n') + '\n')
console.log(`${configList.length} testbench configurations written to ${TB_DIR}/configs.txt`)

console.log(`\n${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)
