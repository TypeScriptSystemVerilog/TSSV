// Generate GrayPointer variants and the inputs for verilatorTB/tb_GrayPointer.sv:
//
// 1. Self-checks against the spec: ports, distinct module names, each module in its own file,
//    and the invalid parameters that throw.
// 2. The testbench configurations (TB_CONFIGS), each emitted one module per file with a lint
//    filelist (emitSplit), plus sv-examples/GrayPointer/tb/:
//    - GrayPointer_tb_configs.svh: per-configuration DUT name, width and syncStages
//    - GrayPointer_tb_vectors.svh: one task per timing diagram in the spec
//    - configs.txt: "<config> <.sv paths>" per line, read by `make graypointer_sim`
//
// Run `make -C verilatorTB graypointer_sim` to generate everything, lint each variant with
// -Wall and simulate each configuration.

import { GrayPointer } from 'tssv/lib/modules/GrayPointer'
import { mkdirSync, readFileSync, writeFileSync } from 'fs'
import { emitSplit } from '../models/emitSplit.js'
import { diagramTasks } from '../models/wavedromVectors.js'

const SPEC = 'doc/modules/GrayPointer/GrayPointer-spec.md'
const OUT = 'sv-examples/GrayPointer'
const TB_DIR = `${OUT}/tb`
const GENERATOR = 'ts/test/modules/test_GrayPointer.ts'

let passed = 0
let failed = 0

function check (label: string, ok: boolean, detail?: string): void {
  if (ok) {
    console.log(`PASS: ${label}`)
    passed++
  } else {
    console.error(`FAIL: ${label}${detail !== undefined ? `\n  ${detail}` : ''}`)
    failed++
  }
}

function expectThrow (label: string, fn: () => unknown, message: string): void {
  try {
    fn()
    check(label, false, 'did not throw')
  } catch (e) {
    const got = (e instanceof Error) ? e.message : String(e)
    check(label, got.includes(message), `expected a message containing '${message}', got '${got}'`)
  }
}

// ============================================ 1. checks against the spec
const SPEC_PORTS = ['clk', 'rst_n', 'inc', 'bin_ptr', 'far_clk', 'far_rst_n', 'far_bin_ptr'].sort().join(' ')

const names = [
  { width: 3n },
  { width: 3n, syncStages: 3n },
  { width: 4n },
  { width: 1n }
].map(p => new GrayPointer(p).name)
check(`pointers that differ in any parameter get different names (${names.join(', ')})`,
  new Set(names).size === names.length)
check('the default name is GrayPointer_<syncStages>_<width>, with syncStages defaulting to 2',
  names[0] === 'GrayPointer_2_3' && new GrayPointer({ width: 3n, syncStages: 2n }).name === names[0])

expectThrow('width 0 throws', () => new GrayPointer({ width: 0n }), 'GrayPointer: width must be at least 1, got 0')
expectThrow('syncStages 1 throws', () => new GrayPointer({ width: 3n, syncStages: 1n }), 'GrayPointer: syncStages must be at least 2, got 1')

// ============================================ 2. testbench configurations
interface TbConfig {
  cfg: string
  width: bigint
  syncStages: bigint
  /** timing diagrams (SVG names in the spec, without the GrayPointer- prefix) to replay */
  diagrams: string[]
}

const TB_CONFIGS: TbConfig[] = [
  { cfg: 'w1_s2', width: 1n, syncStages: 2n, diagrams: [] },
  { cfg: 'w3_s2', width: 3n, syncStages: 2n, diagrams: ['timing'] },
  { cfg: 'w4_s3', width: 4n, syncStages: 3n, diagrams: [] },
  { cfg: 'w6_s2', width: 6n, syncStages: 2n, diagrams: [] }
]

mkdirSync(TB_DIR, { recursive: true })
const header = `// Generated by ${GENERATOR}. Do not edit.\n`
let configs = header
const configList: string[] = []
TB_CONFIGS.forEach((c, i) => {
  const p = new GrayPointer({ width: c.width, syncStages: c.syncStages })
  const files = emitSplit(p, `${OUT}/${p.name}`, GENERATOR)
  const ports = Object.keys((p as unknown as { IOs: Record<string, unknown> }).IOs).sort().join(' ')
  check(`${p.name}: ports match the spec`, ports === SPEC_PORTS, `got: ${ports}\n  spec: ${SPEC_PORTS}`)
  const top = readFileSync(files[files.length - 1] ?? '', 'utf8')
  check(`${p.name}: its file defines only GrayPointer, and its CDCSynchronizer is in a file of its own`,
    files.length === 2 && (top.match(/^module /gm) ?? []).length === 1 && !top.includes('module CDCSynchronizer'),
    `files: ${files.join(', ')}`)
  configList.push(`${c.cfg} ${files.join(' ')}`)
  configs += `\`${i === 0 ? 'ifdef' : 'elsif'} CFG_${c.cfg}\n`
  configs += `  \`define CFG_NAME "${c.cfg}"\n`
  configs += `  \`define GP_DUT ${p.name}\n`
  configs += `  \`define WIDTH ${c.width}\n`
  configs += `  \`define SYNC_STAGES ${c.syncStages}\n`
  configs += `  \`define RUN_DIAGRAMS ${c.diagrams.map(d => `diagram_${d.replace(/-/g, '_')}();`).join(' ')}\n`
  console.log(`${p.name}: testbench config ${c.cfg}`)
})
configs += '`else\n  `error "define one of the CFG_<config> macros"\n`endif\n'
writeFileSync(`${TB_DIR}/GrayPointer_tb_configs.svh`, configs)
writeFileSync(`${TB_DIR}/configs.txt`, configList.join('\n') + '\n')

// ============================================ 3. timing-diagram vectors
// gray_q and sync_0 (the CDCSynchronizer's first flop) are internal: the testbench reads them
// through hierarchical references. Their labels are binary.
const { sv: vectors, names: diagrams } = diagramTasks(SPEC, 'GrayPointer',
  { clock: 'clk', type: 'own_vec_t', fields: ['inc', 'bin_ptr', 'gray_q'] },
  { clock: 'far_clk', type: 'far_vec_t', fields: ['sync_0', 'far_bin_ptr'] },
  ['gray_q', 'sync_0'])
for (const c of TB_CONFIGS) {
  for (const d of c.diagrams) check(`${c.cfg}: the spec has diagram GrayPointer-${d}.svg`, diagrams.includes(d))
}
writeFileSync(`${TB_DIR}/GrayPointer_tb_vectors.svh`, header + vectors)
console.log(`${diagrams.length} timing diagram(s) from ${SPEC} written to ${TB_DIR}/GrayPointer_tb_vectors.svh`)

console.log(`\n${passed} passed, ${failed} failed`)
if (failed > 0) process.exit(1)
