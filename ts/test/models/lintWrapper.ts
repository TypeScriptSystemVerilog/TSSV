// A lint wrapper for a generated module, so it can be linted with `verilator --lint-only -Wall`.
// A module with an interface port can't be the top on its own: nothing would drive the
// interface, and Verilator reports its signals as UNDRIVEN/UNUSED. The wrapper instantiates each
// interface port's interface and brings every signal of it, and every plain port, out to a port
// of its own. Its file includes the module's (guardSV.ts), so it is the top that lints the
// module, and the module's file is never linted alone.
import { type Interface, type Module } from 'tssv/lib/core/TSSV'
import { writeFileSync } from 'fs'
import { guardSV } from './guardSV.js'

interface PortInfo { direction: string, width?: number, isSigned?: boolean }

function decl (direction: string, width: number, isSigned: boolean | undefined, name: string): string {
  const range = width > 1 ? `[${width - 1}:0] ` : ''
  return `${direction === 'input' ? 'input ' : 'output'} logic ${isSigned === true ? 'signed ' : ''}${range}${name}`
}

/**
 * The SV text of `<module>_lint_top`. A plain port keeps its name. Signal `S` of interface port
 * `P` becomes the port `P_S`, in the direction the module sees it.
 */
export function lintWrapper (module: Module, generator: string): string {
  const name = module.name
  const { IOs, interfaces } = module as unknown as { IOs: Record<string, PortInfo>, interfaces: Record<string, Interface> }
  const ports: string[] = []
  const binds: string[] = []
  const body: string[] = []
  for (const [port, io] of Object.entries(IOs)) {
    ports.push(decl(io.direction, io.width ?? 1, io.isSigned, port))
    binds.push(`.${port}(${port})`)
  }
  for (const [port, intf] of Object.entries(interfaces)) {
    if (intf.role === undefined) continue // a local bundle, not a port
    const modport = intf.modports?.[intf.role]
    if (modport === undefined) throw Error(`${name}.${port}: no modport ${intf.role}`)
    body.push(`  ${intf.interfaceName()} ${port}_bus ();`)
    for (const [sig, direction] of Object.entries(modport)) {
      // The module's output is the wrapper's output, and the module's input the wrapper's input
      const width = Number(intf.signals[sig]?.width ?? 1)
      ports.push(decl(direction, width, intf.signals[sig]?.isSigned, `${port}_${sig}`))
      body.push(direction === 'input'
        ? `  assign ${port}_bus.${sig} = ${port}_${sig};`
        : `  assign ${port}_${sig} = ${port}_bus.${sig};`)
    }
    binds.push(`.${port}(${port}_bus)`)
  }
  return `// Lint wrapper for ${name}: generated by ${generator}
module ${name}_lint_top (
  ${ports.join(',\n  ')}
);
${body.join('\n')}

  ${name} dut (
    ${binds.join(',\n    ')}
  );
endmodule
`
}

/**
 * Writes `module` with writeSystemVerilogFiles(), then its lint wrapper to
 * `<dir>/<module>_lint_top.sv`, which includes `<module>.sv`. Returns the paths
 * writeSystemVerilogFiles() wrote, `module`'s last.
 */
export function writeLintWrapped (module: Module, dir: string, generator: string): string[] {
  const design = module.writeSystemVerilogFiles(dir)
  const top = `${module.name}_lint_top`
  writeFileSync(`${dir}/${top}.sv`, guardSV(top, [`${module.name}.sv`], lintWrapper(module, generator)))
  return design
}
