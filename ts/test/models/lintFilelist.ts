// A Verilator argument file that lints a generated top together with the files it depends on.
// `scripts/lint-sv.sh` lints every .sv under sv-examples/, alone by default. A file that needs
// others to lint (a testbench emitted apart from its DUT, a module whose interface definitions
// are in another file, a library of models with no top of its own) is named in one of these
// instead, and lint-sv.sh lints the filelist with `verilator --lint-only -F` and doesn't lint
// that file alone.
import { writeFileSync } from 'fs'
import { posix } from 'path'

/**
 * Writes `<dir>/<top>.f`. `files` are relative to `dir`, as `-F` reads them; a file outside
 * sv-examples/, such as a hand-written testbench in verilatorTB/, is named relative to `dir` too.
 */
export function writeLintFilelist (dir: string, top: string, files: string[], generator: string): void {
  const lines = [
    `// Generated by ${generator}. Lints ${top} with the files it depends on:`,
    `//   verilator --lint-only -F ${posix.join(dir, `${top}.f`)}`,
    `--top-module ${top}`,
    ...files
  ]
  writeFileSync(posix.join(dir, `${top}.f`), lines.join('\n') + '\n')
}
