// Reusable simulation models for the Memory bus (ts/src/interfaces/Memory.ts), written as SV
// text. They are not synthesizable. A testbench file that instantiates one must also compile a
// file that defines the matching memory_<type>_<DATA_WIDTH>_<ADDR_WIDTH> interface, such as the
// DUT's own file.
//
// - memorySlaveModel(): a word-addressed memory behind an `inward` port, with wait states the
//   testbench sets, and checks on what the master does.
// - memoryMasterBfm(): `read` and `write` tasks that drive an `outward` port by the handshake,
//   and count each access's wait states.
//
// Each returns one SV module, named after the interface it connects to:
// memory_slave_<type>_<DATA_WIDTH>_<ADDR_WIDTH> or memory_master_<type>_<DATA_WIDTH>_<ADDR_WIDTH>.
// Used by ts/test/test_RegisterBlock_types.ts and ts/test/test_RegisterBlock_read.ts (TSSV#80).
import { Memory, type Memory_Type } from 'tssv/lib/interfaces/Memory'

export interface MemoryModelOptions {
  /** The bus's type. Default `bidi`. */
  type?: Memory_Type
  /** Default 32. */
  dataWidth?: 32 | 64 | 128 | 256 | 512 | 1024
  /** Default 32. */
  addrWidth?: 32
}

function resolve (opts: MemoryModelOptions): { type: Memory_Type, dw: number, aw: number, iface: string } {
  const bus = new Memory({ type: opts.type, DATA_WIDTH: opts.dataWidth, ADDR_WIDTH: opts.addrWidth })
  return {
    type: opts.type ?? 'bidi',
    dw: opts.dataWidth ?? 32,
    aw: opts.addrWidth ?? 32,
    iface: bus.interfaceName()
  }
}

/** The slave model's SV module name for these options. */
export function memorySlaveName (opts: MemoryModelOptions = {}): string {
  return resolve(opts).iface.replace(/^memory_/, 'memory_slave_')
}

/** The master BFM's SV module name for these options. */
export function memoryMasterName (opts: MemoryModelOptions = {}): string {
  return resolve(opts).iface.replace(/^memory_/, 'memory_master_')
}

/**
 * A memory of `DEPTH` words (an SV parameter) behind an `inward` Memory port. `ADDR` is a byte
 * address: the word index is `ADDR / (DATA_WIDTH/8)`.
 *
 * The testbench controls it through hierarchical references:
 * - `mem[i]`: word `i`. Preload it, or check it after writes. It starts at 0.
 * - `wait_states`: how many cycles `READY` stays low after each request. Default 0.
 * - `errors`: contract violations seen, each also printed. Check it is 0 at the end.
 * - `reads`, `writes`: accesses completed.
 *
 * It flags a request while `READY` is low, `RE` and `WE` together, an `ADDR`/`DATA_WR`/`WSTRB`
 * that changes while `READY` is low, and an index past `DEPTH`. A write applies the bytes whose
 * `WSTRB` bit is set. `WSTRB` has only `ADDR_WIDTH/8` bits until TSSV#81, so bytes above those
 * are always written.
 */
export function memorySlaveModel (opts: MemoryModelOptions = {}): string {
  const { type, dw, aw, iface } = resolve(opts)
  const name = memorySlaveName(opts)
  const writes = type !== 'rd_only'
  const reads = type !== 'wr_only'
  const sw = aw / 8
  const re = reads ? 'bus.RE' : "1'b0"
  const we = writes ? 'bus.WE' : "1'b0"
  const dataArgs = writes ? `, input logic [${dw - 1}:0] data, input logic [${sw - 1}:0] strb` : ''
  const writeAccess = !writes
    ? ''
    : `    if (we) begin
      for (int b = 0; b < BYTES; b++)
        if (b >= ${sw} || strb[b]) mem[idx][8*b +: 8] = data[8*b +: 8];
      writes++;
      return;
    end
`
  const readAccess = reads ? '    bus.DATA_RD <= mem[idx];\n    reads++;\n' : ''
  return `// ${name}: Memory slave model, generated by ts/test/models/MemoryModels.ts
module ${name} #(
  parameter int DEPTH = 16
) (
  input logic clk,
  input logic rst_b,
  ${iface}.inward bus
);
  localparam int BYTES = ${dw / 8};

  logic [${dw - 1}:0] mem [DEPTH];
  int wait_states = 0;
  int errors = 0;
  int reads = 0;
  int writes = 0;

  // The access waiting out its wait states
  logic busy = 1'b0;
  int count = 0;
  logic p_we = 1'b0;
  logic [${aw - 1}:0] p_addr = '0;
${writes ? `  logic [${dw - 1}:0] p_data = '0;\n  logic [${sw - 1}:0] p_strb = '0;\n` : ''}
  initial foreach (mem[i]) mem[i] = '0;

  function automatic void fail (input string what);
    errors++;
    $display("ERROR %0t: ${name} (%m): %s", $time, what);
  endfunction

  task automatic access (input logic we, input logic [${aw - 1}:0] addr${dataArgs});
    int idx;
    idx = int'(addr / BYTES);
    if (idx >= DEPTH) begin
      fail($sformatf("ADDR 0x%0h is word %0d, past DEPTH %0d", addr, idx, DEPTH));
      return;
    end
${writeAccess}${readAccess}  endtask

  always @(posedge clk or negedge rst_b) begin
    if (!rst_b) begin
      bus.READY <= 1'b1;
      busy <= 1'b0;
    end else if (busy) begin
      if (${re} || ${we}) fail("request while READY is low");
      if (bus.ADDR !== p_addr) fail("ADDR changed while READY is low");
${writes ? `      if (p_we && (bus.DATA_WR !== p_data || bus.WSTRB !== p_strb)) fail("DATA_WR or WSTRB changed while READY is low");\n` : ''}      if (count == 0) begin
        access(p_we, p_addr${writes ? ', p_data, p_strb' : ''});
        bus.READY <= 1'b1;
        busy <= 1'b0;
      end else begin
        count <= count - 1;
      end
    end else if (${re} || ${we}) begin
      if (${re} && ${we}) fail("RE and WE together");
      if (wait_states == 0) begin
        access(${we}, bus.ADDR${writes ? ', bus.DATA_WR, bus.WSTRB' : ''});
      end else begin
        busy <= 1'b1;
        count <= wait_states - 1;
        bus.READY <= 1'b0;
        p_we <= ${we};
        p_addr <= bus.ADDR;
${writes ? '        p_data <= bus.DATA_WR;\n        p_strb <= bus.WSTRB;\n' : ''}      end
    end
  end
endmodule
`
}

/**
 * A master BFM on an `outward` Memory port. Inputs change on the falling edge of `clk`.
 *
 * - `write(addr, data, strb)` (not on `rd_only`) and `read(addr, data)` (not on `wr_only`) wait
 *   for `READY`, raise `WE` or `RE` for one cycle, and return 1 ns after the falling edge in the
 *   first cycle `READY` is high again. `ADDR` and the write data stay as they were until the next
 *   access. `read` returns `DATA_RD` from that cycle.
 * - `waits` is the number of cycles `READY` was low during the last access.
 */
export function memoryMasterBfm (opts: MemoryModelOptions = {}): string {
  const { type, dw, aw, iface } = resolve(opts)
  const name = memoryMasterName(opts)
  const writes = type !== 'rd_only'
  const reads = type !== 'wr_only'
  const sw = aw / 8
  return `// ${name}: Memory master BFM, generated by ts/test/models/MemoryModels.ts
module ${name} (
  input logic clk,
  ${iface}.outward bus
);
  int waits = 0;

  initial begin
    bus.ADDR = '0;
${reads ? '    bus.RE = 1\'b0;\n' : ''}${writes ? '    bus.WE = 1\'b0;\n    bus.DATA_WR = \'0;\n    bus.WSTRB = \'0;\n' : ''}  end

  // Waits for a falling edge where READY is high: a request may start there
  task automatic idle ();
    @(negedge clk);
    while (!bus.READY) @(negedge clk);
  endtask

  // From the falling edge after the capture edge, counts the cycles READY is low
  task automatic settle ();
    waits = 0;
    #1;
    while (!bus.READY) begin
      waits++;
      @(negedge clk);
      #1;
    end
  endtask
${writes
  ? `
  task automatic write (input logic [${aw - 1}:0] addr, input logic [${dw - 1}:0] data,
                        input logic [${sw - 1}:0] strb = '1);
    idle();
    bus.ADDR = addr;
    bus.DATA_WR = data;
    bus.WSTRB = strb;
    bus.WE = 1'b1;
    @(negedge clk);
    bus.WE = 1'b0;
    settle();
  endtask
`
  : ''}${reads
  ? `
  task automatic read (input logic [${aw - 1}:0] addr, output logic [${dw - 1}:0] data);
    idle();
    bus.ADDR = addr;
    bus.RE = 1'b1;
    @(negedge clk);
    bus.RE = 1'b0;
    settle();
    data = bus.DATA_RD;
  endtask
`
  : ''}endmodule
`
}
