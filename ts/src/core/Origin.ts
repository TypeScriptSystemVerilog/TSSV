// Where a generated module or interface came from, for the file header that
// writeSystemVerilogFiles() puts on each file it generates: the class that built it, the repo that
// class is in, its source file and its spec. The constructors of Module and Interface call
// originOf() while their caller's frames are still on the stack.
import { existsSync, readFileSync } from 'fs'
import { dirname, join, relative, sep } from 'path'
import { fileURLToPath } from 'url'

/** Where a module or interface came from */
export interface Origin {
  /** the class that built it: the most derived class, or `Module` or `Interface` itself */
  className: string
  /** the repo its source is in: the `name` in the `package.json` nearest the source file */
  repo?: string
  /** the folder that `package.json` is in, which `file` and the spec are relative to */
  root?: string
  /**
   * the source file, relative to `root` with `/` separators: the class's own file, or for a
   * `Module` or `Interface` built directly, the file that called the constructor. A file compiled
   * from `ts/` to `out/` is named by its TypeScript source when that is there.
   */
  file?: string
  /** the class's spec, relative to `root`: its own static `spec`, not one it inherits */
  spec?: string
}

// The package each folder is in, so each folder is looked up once
const packages = new Map<string, { root: string, name: string } | undefined>()

/** The package a folder is in: the nearest `package.json` at or above it that has a `name` */
function packageOf (dir: string): { root: string, name: string } | undefined {
  if (packages.has(dir)) return packages.get(dir)
  let found: { root: string, name: string } | undefined
  const file = join(dir, 'package.json')
  const name = existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as { name?: unknown }).name : undefined
  if (typeof name === 'string') {
    found = { root: dir, name }
  } else if (dirname(dir) !== dir) {
    found = packageOf(dirname(dir))
  }
  packages.set(dir, found)
  return found
}

/** The file a stack frame is in: `at f (/a/b.js:1:2)` or `at /a/b.js:1:2`, `file://` URLs included */
function frameFile (frame: string): string | undefined {
  const m = /\(([^()]+):\d+:\d+\)\s*$/.exec(frame) ?? /^\s*at ([^()\s]+):\d+:\d+\s*$/.exec(frame)
  if (m === null) return undefined
  return m[1].startsWith('file://') ? fileURLToPath(m[1]) : m[1]
}

// The origin of each subclass, which is the same for all its instances
const byClass = new Map<object, Origin>()

/**
 * Where an instance of `target` comes from, called by `base`'s constructor (`Module` or
 * `Interface`). For a subclass, the source is the file of its constructor's frame. For `base`
 * itself, it is the file of the frame that called the constructor. The spec is `target`'s own
 * static `spec`.
 */
export function originOf (target: { name: string }, base: { name: string }): Origin {
  const cached = byClass.get(target)
  if (cached !== undefined) return cached
  const limit = Error.stackTraceLimit
  Error.stackTraceLimit = 64
  const frames = (new Error().stack ?? '').split('\n').slice(1)
  Error.stackTraceLimit = limit

  const own = target !== base
  const at = frames.findIndex(f => f.includes(`at new ${target.name} (`))
  const frame = at < 0 ? undefined : own ? frames[at] : frames[at + 1]
  const path = frame === undefined ? undefined : frameFile(frame)
  const origin: Origin = { className: target.name }
  const pkg = path === undefined ? undefined : packageOf(dirname(path))
  if (path !== undefined && pkg !== undefined) {
    let file = relative(pkg.root, path).split(sep).join('/')
    const ts = /^out\/(.*)\.js$/.exec(file)
    if (ts !== null && existsSync(join(pkg.root, 'ts', `${ts[1]}.ts`))) file = `ts/${ts[1]}.ts`
    Object.assign(origin, { repo: pkg.name, root: pkg.root, file })
  }
  const spec = Object.prototype.hasOwnProperty.call(target, 'spec') ? (target as { spec?: unknown }).spec : undefined
  if (spec !== undefined) {
    if (typeof spec !== 'string' || spec === '') throw Error(`${target.name}: spec must be a path, relative to its repo`)
    origin.spec = spec
  }
  // A Module or Interface built directly takes its caller's file, which differs per instance
  if (own) byClass.set(target, origin)
  return origin
}

/**
 * The file header that writeSystemVerilogFiles() puts at the top of a generated file, one comment
 * per line, for `name`, which `origin` built. A spec that doesn't exist in its repo throws.
 */
export function generatedHeader (name: string, origin: Origin): string {
  const lines = ["// Generated by TSSV. Don't edit this file: change its generator and regenerate."]
  lines.push(`// Generator: ${origin.className}` + (origin.file === undefined ? '' : `, ${origin.repo ?? ''} ${origin.file}`))
  if (origin.spec !== undefined) {
    if (origin.root !== undefined && !existsSync(join(origin.root, origin.spec))) {
      throw Error(`writeSystemVerilogFiles: ${name}: the spec of ${origin.className}, ${origin.spec}, ` +
        `isn't in ${origin.repo ?? origin.root}`)
    }
    lines.push(`// Spec: ${origin.spec}`)
  }
  return lines.join('\n') + '\n'
}
